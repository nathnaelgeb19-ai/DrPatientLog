def _execute(obj, query, params=()):
    if DB_BACKEND == "postgresql":
        query = query.replace("?", "%s")
    return obj.execute(query, params) if params else obj.execute(query)


@contextmanager
def get_conn():
    """
    Return a database connection.

    Local PC:
        SQLite

    Render:
        PostgreSQL / Neon
    """

    if DB_BACKEND == "postgresql":
        with pg_pool.connection() as conn:
            try:
                yield conn
                conn.commit()
            except Exception:
                conn.rollback()
                raise

    else:
        # Local development continues to use the existing SQLite database.
        conn = sqlite3.connect(
            DB_FILE,
            timeout=30,
        )
        conn.row_factory = sqlite3.Row

        try:
            _execute(conn, "PRAGMA journal_mode=WAL")
            _execute(conn, "PRAGMA busy_timeout=30000")
        except Exception:
            pass

        try:
            yield conn
            conn.commit()
        except Exception:
            conn.rollback()
            raise
        finally:
            conn.close()


def hash_password(password: str) -> str:
    salt = secrets.token_hex(16)
    digest = hashlib.pbkdf2_hmac(
        "sha256",
        (password or "").encode("utf-8"),
        salt.encode("utf-8"),
        120000,
    ).hex()
    return f"{salt}${digest}"


def verify_password(password: str, stored_hash: str) -> bool:
    if not stored_hash or "$" not in stored_hash:
        return False
    salt, expected = stored_hash.split("$", 1)
    digest = hashlib.pbkdf2_hmac(
        "sha256",
        (password or "").encode("utf-8"),
        salt.encode("utf-8"),
        120000,
    ).hex()
    return secrets.compare_digest(digest, expected)


